//! `import-steamworks`: writes the vtable table of `steamworks-abi.md` §2.4
//! from the interface wrappers in Proton's `lsteamclient`.
//!
//! Proton's `lsteamclient` (<https://github.com/ValveSoftware/Proton>)
//! is Valve's open-source bridge between Windows games and the Linux
//! client library. Its generated `win*.c` files hold, for every interface
//! version that a published Steamworks SDK declares, the methods in vtable
//! order with C signatures and the bytes each takes on the 32-bit
//! `thiscall` stack. Only those facts are read: names, order and types.
//! No code is copied (SPEC RE-2).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, bail};

const OUTPUT: &str = "docs/spec/steamworks/vtables.txt";

/// Types passed or returned by value that are not plain integers or
/// floats, with their size on 32-bit Windows (`steamworks-abi.md` §2.4).
/// The import checks every size against Proton's stack byte counts.
const STRUCTS: &[(&str, u32)] = &[
    ("CSteamID", 8),
    ("CGameID", 8),
    ("SteamIPAddress_t", 20),
    ("SteamPartyBeaconLocation_t", 12),
    ("RemoteStorageUpdatePublishedFileRequest_t", 40),
    ("InputAnalogActionData_t", 13),
    ("InputDigitalActionData_t", 2),
    ("InputMotionData_t", 40),
    ("ControllerAnalogActionData_t", 13),
    ("ControllerDigitalActionData_t", 2),
    ("ControllerMotionData_t", 40),
];

struct Function {
    ret: String,
    params: Vec<(String, String)>,
}

struct Version {
    interface: String,
    version: String,
    slots: Vec<String>,
}

pub fn import(dir: &Path) -> anyhow::Result<()> {
    let mut functions: BTreeMap<String, Function> = BTreeMap::new();
    let mut stack: BTreeMap<String, u32> = BTreeMap::new();
    let mut versions: Vec<Version> = Vec::new();

    let mut sources = Vec::new();
    for entry in std::fs::read_dir(dir).with_context(|| format!("listing {}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "c") {
            sources.push(path);
        }
    }
    sources.sort();
    if sources.is_empty() {
        bail!(
            "{} holds no .c files; pass Proton's lsteamclient directory",
            dir.display()
        );
    }
    for path in &sources {
        let text =
            std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
        parse_functions(&text, &mut functions)?;
        parse_stack_sizes(&text, &mut stack)?;
        let name = path.file_name().unwrap_or_default().to_string_lossy();
        if let Some(interface) = name.strip_prefix("win").and_then(|n| n.strip_suffix(".c")) {
            parse_vtables(&text, interface, &mut versions)?;
        }
    }
    versions.sort_by(|a, b| {
        (a.interface.as_str(), a.version.as_str()).cmp(&(b.interface.as_str(), b.version.as_str()))
    });
    if versions.is_empty() {
        bail!("no vtables found under {}", dir.display());
    }

    let commit = std::process::Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(["rev-parse", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_else(|| "unknown".into());

    let mut out = String::new();
    out.push_str("# The Steamworks interface vtables (steamworks-abi.md §2.4).\n");
    out.push_str("# Generated by `cargo xtask import-steamworks`; do not edit by hand.\n");
    let _ = writeln!(out, "# Source: Proton lsteamclient, commit {commit}.");
    out.push_str("#\n");
    out.push_str("# [<version string> <interface>] starts an interface version. Each line\n");
    out.push_str("# under it is one vtable slot, in order: <slot> <method>(<params>) -> <type>.\n");
    let mut slots = 0;
    for v in &versions {
        let _ = writeln!(out, "\n[{} {}]", v.version, v.interface);
        for (i, name) in v.slots.iter().enumerate() {
            let f = functions
                .get(name)
                .with_context(|| format!("{name} is in a vtable but never defined"))?;
            let (ret, params) = normalise(name, f)?;
            let expected = *stack
                .get(name)
                .with_context(|| format!("{name} has no thiscall wrapper"))?;
            let computed = stack_bytes(&ret, &params)?;
            if computed != expected {
                bail!("{name}: the parameters take {computed} bytes, Proton says {expected}");
            }
            let method = name
                .strip_prefix(&format!("win{}_{}_", v.interface, symbol(&v.version)))
                .with_context(|| format!("{name} does not belong to {}", v.version))?;
            let list: Vec<String> = params.iter().map(|(n, t)| format!("{n}: {t}")).collect();
            let _ = writeln!(out, "{i} {method}({}) -> {ret}", list.join(", "));
            slots += 1;
        }
    }
    let path = crate::workspace_root().join(OUTPUT);
    std::fs::create_dir_all(path.parent().expect("has a parent"))?;
    std::fs::write(&path, out).with_context(|| format!("writing {}", path.display()))?;
    println!(
        "wrote {} interface versions, {slots} slots, to {OUTPUT}",
        versions.len()
    );
    Ok(())
}

/// The version string as it appears in Proton's symbol names.
fn symbol(version: &str) -> String {
    version
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// Finds `<ret> __thiscall win<name>(<params>)` definitions. Parameters
/// may span lines and hold function pointer types, so the parameter list
/// is read up to its balancing parenthesis.
fn parse_functions(text: &str, out: &mut BTreeMap<String, Function>) -> anyhow::Result<()> {
    let mut rest = text;
    while let Some(at) = rest.find("__thiscall win") {
        let line_start = rest[..at].rfind('\n').map_or(0, |i| i + 1);
        let ret = rest[line_start..at].trim().to_owned();
        let after = &rest[at + "__thiscall ".len()..];
        let Some(open) = after.find('(') else { break };
        let name = after[..open].trim().to_owned();
        let mut depth = 0;
        let mut close = None;
        for (i, c) in after[open..].char_indices() {
            match c {
                '(' => depth += 1,
                ')' => {
                    depth -= 1;
                    if depth == 0 {
                        close = Some(open + i);
                        break;
                    }
                }
                _ => {}
            }
        }
        let close = close.with_context(|| format!("{name}: unbalanced parameter list"))?;
        let list = &after[open + 1..close];
        rest = &after[close..];
        // A declaration that starts mid-line (a macro, a cast) is not a
        // definition.
        if ret.is_empty()
            || ret.contains('(')
            || ret.contains('=')
            || ret.starts_with("extern")
            || out.contains_key(&name)
        {
            continue;
        }
        let params = split_params(list)
            .into_iter()
            .filter(|p| !p.is_empty())
            .collect::<Vec<_>>();
        let Some(first) = params.first() else {
            bail!("{name}: no `this` parameter");
        };
        if !first.contains("w_iface") {
            bail!("{name}: the first parameter is {first:?}, not `this`");
        }
        let params = params[1..]
            .iter()
            .enumerate()
            .map(|(i, p)| split_param(p, i))
            .collect();
        out.insert(name, Function { ret, params });
    }
    Ok(())
}

/// Splits at top-level commas.
fn split_params(list: &str) -> Vec<String> {
    let mut parts = Vec::new();
    let mut depth = 0;
    let mut cur = String::new();
    for c in list.chars() {
        match c {
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                parts.push(cur.split_whitespace().collect::<Vec<_>>().join(" "));
                cur.clear();
                continue;
            }
            _ => {}
        }
        cur.push(c);
    }
    parts.push(cur.split_whitespace().collect::<Vec<_>>().join(" "));
    parts
}

/// One C parameter as (name, C type).
fn split_param(p: &str, index: usize) -> (String, String) {
    // A function pointer or a pointer to an array: `ret (*name)(...)`,
    // `char (*name)[N]`.
    if let Some(open) = p.find("(*") {
        let inner = &p[open + 2..];
        let end = inner.find(')').unwrap_or(inner.len());
        let name = inner[..end]
            .split_whitespace()
            .last()
            .unwrap_or_default()
            .to_owned();
        return (name, "(*)".into());
    }
    let p = p.trim();
    let split = p
        .rfind(|c: char| c == '*' || c.is_whitespace())
        .map(|i| i + 1)
        .unwrap_or(0);
    let (ty, name) = p.split_at(split);
    let name = name.trim();
    if name.is_empty() || ty.trim().is_empty() || is_type_word(name) {
        return (format!("_{index}"), p.to_owned());
    }
    (name.to_owned(), ty.trim().to_owned())
}

fn is_type_word(s: &str) -> bool {
    matches!(
        s,
        "void"
            | "char"
            | "float"
            | "double"
            | "int8_t"
            | "uint8_t"
            | "int16_t"
            | "uint16_t"
            | "int32_t"
            | "uint32_t"
            | "int64_t"
            | "uint64_t"
    )
}

fn parse_stack_sizes(text: &str, out: &mut BTreeMap<String, u32>) -> anyhow::Result<()> {
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("DEFINE_THISCALL_WRAPPER(") else {
            continue;
        };
        let rest = rest.trim_end_matches(')');
        let Some((name, size)) = rest.split_once(',') else {
            bail!("malformed wrapper line {line:?}");
        };
        let size: u32 = size
            .trim()
            .parse()
            .with_context(|| format!("malformed size in {line:?}"))?;
        out.insert(name.trim().to_owned(), size);
    }
    Ok(())
}

/// Reads `__ASM_VTABLE(win<I>_<V>, VTABLE_ADD_FUNC(...)...);` blocks and
/// the version strings that `alloc_vtable` names them by.
fn parse_vtables(text: &str, interface: &str, out: &mut Vec<Version>) -> anyhow::Result<()> {
    let mut strings = BTreeMap::new();
    let mut rest = text;
    while let Some(at) = rest.find("alloc_vtable(&") {
        let after = &rest[at + "alloc_vtable(&".len()..];
        let end = after.find(')').context("unterminated alloc_vtable")?;
        let args: Vec<&str> = after[..end].split(',').map(str::trim).collect();
        if let [table, _, version] = args[..] {
            let table = table.trim_end_matches("_vtable").to_owned();
            strings.insert(table, version.trim_matches('"').to_owned());
        }
        rest = &after[end..];
    }

    let mut rest = text;
    while let Some(at) = rest.find("__ASM_VTABLE(") {
        let after = &rest[at + "__ASM_VTABLE(".len()..];
        let comma = after.find(',').context("malformed __ASM_VTABLE")?;
        let table = after[..comma].trim().to_owned();
        let end = after.find(");").context("unterminated __ASM_VTABLE")?;
        let slots = after[comma..end]
            .lines()
            .filter_map(|l| {
                l.trim()
                    .strip_prefix("VTABLE_ADD_FUNC(")
                    .map(|n| n.trim_end_matches(')').to_owned())
            })
            .collect::<Vec<_>>();
        rest = &after[end..];
        let version = strings
            .get(&table)
            .with_context(|| format!("{table} has no version string"))?
            .clone();
        if !table.starts_with(&format!("win{interface}_")) {
            bail!("{table} is not an {interface} vtable");
        }
        out.push(Version {
            interface: interface.to_owned(),
            version,
            slots,
        });
    }
    Ok(())
}

/// Maps Proton's C types to the table's types (`steamworks-abi.md` §2.4).
/// A Windows wrapper returns a struct through a `_ret` pointer; the
/// table lists it as returned by value.
fn normalise(name: &str, f: &Function) -> anyhow::Result<(String, Vec<(String, String)>)> {
    let mut params = f.params.as_slice();
    let ret = if params.first().is_some_and(|(n, _)| n == "_ret") {
        let (_, ty) = &params[0];
        params = &params[1..];
        let base = ty.trim_end_matches('*').trim();
        struct_name(base).with_context(|| format!("{name}: unknown returned struct {base}"))?
    } else {
        value_type(name, &f.ret, true)?
    };
    let params = params
        .iter()
        .map(|(n, t)| Ok((n.clone(), value_type(name, t, false)?)))
        .collect::<anyhow::Result<_>>()?;
    Ok((ret, params))
}

fn struct_name(c: &str) -> Option<String> {
    let c = c.trim_start_matches("const ").trim_start_matches("w_");
    STRUCTS
        .iter()
        .find(|(n, _)| *n == c)
        .map(|(n, _)| (*n).to_owned())
}

fn value_type(name: &str, c: &str, is_return: bool) -> anyhow::Result<String> {
    let c = c.trim();
    if c.contains('*') || c == "(*)" {
        let pointee = c.trim_end_matches('*').trim();
        if is_return && (pointee == "const char" || pointee == "char") {
            return Ok("str".into());
        }
        return Ok("ptr".into());
    }
    let c = c.trim_start_matches("const ").trim();
    Ok(match c {
        "void" if is_return => "void",
        "int8_t" | "char" => "i8",
        "uint8_t" => "u8",
        "int16_t" => "i16",
        "uint16_t" => "u16",
        "int32_t" => "i32",
        "uint32_t" => "u32",
        "int64_t" => "i64",
        "uint64_t" => "u64",
        "float" => "f32",
        "double" => "f64",
        other => {
            return struct_name(other).with_context(|| format!("{name}: unknown type {other:?}"));
        }
    }
    .to_owned())
}

/// Bytes on the 32-bit `thiscall` stack, `this` included: each argument
/// takes its size rounded up to 4, and a struct return adds its pointer.
pub fn stack_bytes(ret: &str, params: &[(String, String)]) -> anyhow::Result<u32> {
    let mut n = 4;
    if STRUCTS.iter().any(|(s, _)| *s == ret) {
        n += 4;
    }
    for (_, t) in params {
        n += match t.as_str() {
            "i8" | "u8" | "i16" | "u16" | "i32" | "u32" | "f32" | "ptr" => 4,
            "i64" | "u64" | "f64" => 8,
            s => {
                let size = STRUCTS
                    .iter()
                    .find(|(n, _)| *n == s)
                    .map(|(_, z)| *z)
                    .with_context(|| format!("no size for {s}"))?;
                size.div_ceil(4) * 4
            }
        };
    }
    Ok(n)
}
